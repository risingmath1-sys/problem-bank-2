def _normalize_chapter(raw: str) -> str:
    """챕터명 정규화: 공백 제거, 소문자 변환하지 않음 (한글이므로)."""
    return raw.replace(" ", "").replace("\u200b", "").strip()


def get_unit_code(ebs_subject: str, chapter_name: str) -> str | None:
    """
    EBS 파일명에서 파싱한 과목 + 챕터명으로 중단원 코드를 반환.

    Args:
        ebs_subject:  파일명 과목 표기 (예: "수학Ⅰ", "미적분", "확률과통계")
        chapter_name: 파일명 챕터명 (예: "지수와로그", "수열의합과수학적귀납법")

    Returns:
        중단원 코드 문자열 (예: "H1") 또는 None (매핑 없으면)
    """
    subj = _SUBJECT_ALIAS.get(ebs_subject, ebs_subject)
    subj_map = CHAPTER_MAP.get(subj)
    if subj_map is None:
        return None
    key = _normalize_chapter(chapter_name)
    return subj_map.get(key)


