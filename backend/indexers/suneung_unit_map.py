def parse_ebs_filename(filename: str) -> dict | None:
    """
    EBS HWP 파일명 파싱 → {source_type, subject_raw, year, chapter_no, chapter_name} 반환.

    지원 패턴:
      EBS수능특강수학Ⅰ[2025]_01_지수와로그.hwp
      EBS수능완성수학Ⅱ[2024]_03_도함수의활용.hwp
      EBS수능특강확률과통계[2026]_02_중복조합과이항정리.hwp
      EBS수능특강기하[2025]_04_벡터의연산.hwp

    과목명으로 인식하는 문자열 (EBS수능[접미사] 바로 뒤):
      수학Ⅰ, 수학Ⅱ, 미적분, 확률과통계, 기하

    Args:
        filename: HWP 파일명 (경로 제외, 확장자 포함 가능)

    Returns:
        dict 또는 None (파싱 실패 시)
    """
    # 과목명은 고정 목록으로 명시 — 앞에 붙는 접미사(특강, 완성, ...)와 명확히 분리
    subject_pattern = "|".join([
        r"수학Ⅰ", r"수학Ⅱ", r"수학I", r"수학II", r"수학1", r"수학2",
        r"미적분", r"확률과통계", r"확통", r"기하",
    ])
    pattern = re.compile(
        r"EBS수능"
        r"(?P<source_suffix>[가-힣]+?)"       # '특강' / '완성' 등 (non-greedy)
        r"-?"                                  # 선택적 하이픈 (예: 수능완성-수학2)
        r"(?P<subject>" + subject_pattern + r")"  # 과목명 (고정 목록)
        r"\[(?P<year>\d{4})\]"               # [2025]
        r"_(?P<ch_no>\d+)"                   # _01
        r"_(?P<ch_name>[^_.]+)"              # _지수와로그 (괄호 포함 허용)
    )
    m = pattern.search(filename)
    if not m:
        return None
    return {
        "source_suffix": m.group("source_suffix"),   # 특강 / 완성
        "subject_raw":   m.group("subject"),
        "year":          int(m.group("year")),
        "chapter_no":    int(m.group("ch_no")),
        "chapter_name":  m.group("ch_name"),
    }

